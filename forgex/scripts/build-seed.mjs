// Builds supabase/seed.sql from supabase/skill-vault.json.
// Usage: npm run seed:build
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { skills } = JSON.parse(readFileSync(join(root, "supabase/skill-vault.json"), "utf8"));

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

function questionsFor(skill) {
  const out = [];
  if (skill.tools?.length) {
    out.push({ prompt: "Which tools can you use without a tutorial?", type: "multi", options: skill.tools });
  }
  out.push(
    { prompt: "Link one piece of work you made in the last 6 months.", type: "link", options: [] },
    {
      prompt: `Could you ${skill.one_hour_test} in 1 hour?`,
      type: "single",
      options: ["Yes", "With help", "No"],
    },
    {
      prompt: "Have you delivered this for a real client, club or event?",
      type: "single_link",
      options: ["Yes", "No"],
    },
  );
  return out.map((x, i) => ({ ...x, id: `${skill.id}-q${i + 1}`, order: i + 1 }));
}

const ids = new Set();
for (const s of skills) {
  if (ids.has(s.id)) throw new Error(`duplicate skill id ${s.id}`);
  ids.add(s.id);
}

let sql = `-- GENERATED by scripts/build-seed.mjs from supabase/skill-vault.json. Do not edit by hand.\n\n`;
sql += `insert into skills (id, name, category, one_hour_test) values\n`;
sql += skills.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.category)}, ${q(s.one_hour_test)})`).join(",\n");
sql += `\non conflict (id) do update set name = excluded.name, category = excluded.category, one_hour_test = excluded.one_hour_test;\n\n`;

const rows = skills.flatMap((s) => questionsFor(s).map((x) => ({ ...x, skill_id: s.id })));
sql += `insert into skill_questions (id, skill_id, prompt, type, options_json, "order") values\n`;
sql += rows
  .map((r) => `  (${q(r.id)}, ${q(r.skill_id)}, ${q(r.prompt)}, ${q(r.type)}, ${json(r.options)}, ${r.order})`)
  .join(",\n");
sql += `\non conflict (id) do update set prompt = excluded.prompt, type = excluded.type, options_json = excluded.options_json, "order" = excluded."order";\n\n`;

sql += `-- Pilot institute (§7). Add more via the admin panel or SQL.\n`;
sql += `insert into institutes (name, slug, domain) values ('IIT Jammu', 'iit-jammu', 'iitjammu.ac.in')\non conflict (slug) do nothing;\n`;

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`seed.sql: ${skills.length} skills, ${rows.length} questions`);
